import { keywordsFor } from "./keywords.mjs";

/**
 * Curated timeline. Historical entries use primary sources (papers, official
 * announcements, institutional records). 2025–2026 entries were checked against
 * the captured OpenRouter, Hugging Face, arXiv and official-news payloads.
 * Seeds are inserted by the first sync, never by migration SQL.
 */
export const SEED_VERSION = "2026.10.25.1";

function seed(def) {
  const date = def.date;
  const precision =
    def.precision || (date.length === 4 ? "year" : date.length === 7 ? "month" : "day");
  const sortDate =
    def.sortDate ||
    (date.length === 4 ? `${date}-01-01` : date.length === 7 ? `${date}-01` : date);
  const year = Number(date.slice(0, 4));
  const titleEn = def.titleEn || def.title;
  const sources = (def.sources || []).map((s) => ({
    name: s.name,
    family: s.family || "official",
    title: s.title || titleEn,
    url: s.url,
    publishedAt: s.date || sortDate,
    externalId: s.url,
  }));
  const modelKey = def.modelKey || null;
  const familyKey = modelKey ? modelFamilyKey(modelKey) : null;
  const aliases = modelKey ? modelAliasesOf(modelKey) : [];
  return {
    seedId: def.id,
    origin: "seed",
    category: def.category,
    title: def.title,
    titleEn,
    summary: def.summary,
    summaryKind: "curated",
    eventDate: date,
    datePrecision: precision,
    sortDate,
    year,
    organization: def.org || null,
    modelName: def.modelName || null,
    tags: keywordsFor({
      tags: def.tags,
      title: def.title,
      titleEn,
      summary: def.summary,
      organization: def.org,
      modelName: def.modelName,
      category: def.category,
    }),
    meta: {
      research_note: def.note || "官方页面核对",
      ...(def.meta || {}),
      ...(modelKey ? { modelKey, aliases, familyKey, vendorKey: def.vendor || null } : {}),
    },
    modelKey,
    familyKey,
    aliases,
    urls: sources.map((s) => normalizeUrl(s.url)).filter(Boolean),
    evidence: sources,
    tokens: titleTokens(titleEn),
    signals: {
      headLab: def.headLab ?? Boolean(modelKey),
      hnPoints: 0,
      hfLikes: 0,
      officialPrimary: true,
      mediaOnly: false,
    },
    curatedImportance: def.importance,
  };
}

