"""The frozen seed, loaded once from `app/data/seed.json`.

The file is generated by `scripts/export-seed.mjs` and checked in: it is the
only source of curated history, so a runtime change to the JS libraries can no
longer silently rewrite 158 entries.
"""

from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path
from typing import Any

SEED_PATH = Path(__file__).resolve().parent.parent / "data" / "seed.json"


@lru_cache(maxsize=1)
def _payload() -> dict[str, Any]:
    with SEED_PATH.open(encoding="utf-8") as handle:
        return json.load(handle)


def seed_version() -> str:
    return str(_payload()["seedVersion"])


def seed_events() -> list[dict[str, Any]]:
    return _payload()["events"]


SEED_VERSION = seed_version()
SEED_EVENTS = seed_events()
